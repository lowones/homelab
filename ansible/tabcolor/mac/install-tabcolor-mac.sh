#!/bin/bash
# Tab marker for a Mac (zsh). Mirrors the Ansible tabcolor role, which only
# covers bash hosts in /etc/profile.d. Run as your normal user, no sudo:
#   bash install-tabcolor-mac.sh <name> <colour>
#   bash install-tabcolor-mac.sh neverland white
# Colours: red orange yellow green blue purple brown black white
# Safe to re-run: rewrites ~/.config/tabcolor/tabcolor.zsh, keeps one source line in ~/.zshrc.
set -euo pipefail

NAME=${1:?usage: install-tabcolor-mac.sh <name> <colour>   (e.g. neverland white)}
COLOUR=${2:?usage: install-tabcolor-mac.sh <name> <colour>   (red orange yellow green blue purple brown black white)}

case "$COLOUR" in
  red)    EMOJI="🟥"; R=200; G=40;  B=40  ;;
  orange) EMOJI="🟧"; R=240; G=140; B=30  ;;
  yellow) EMOJI="🟨"; R=245; G=205; B=20  ;;
  green)  EMOJI="🟩"; R=40;  G=170; B=90  ;;
  blue)   EMOJI="🟦"; R=40;  G=90;  B=200 ;;
  purple) EMOJI="🟪"; R=140; G=70;  B=190 ;;
  brown)  EMOJI="🟫"; R=140; G=90;  B=50  ;;
  black)  EMOJI="⬛"; R=60;  G=60;  B=60  ;;
  white)  EMOJI="⬜"; R=255; G=255; B=255 ;;
  *) echo "unknown colour: $COLOUR"; exit 1 ;;
esac

DIR="$HOME/.config/tabcolor"
FILE="$DIR/tabcolor.zsh"
ZSHRC="$HOME/.zshrc"
mkdir -p "$DIR"

{
  echo "# Generated by install-tabcolor-mac.sh (lowones/homelab -> ansible/tabcolor/mac). Do not edit in place."
  echo "TC_R=$R; TC_G=$G; TC_B=$B"
  echo "TC_MARK='$EMOJI $NAME'"
  cat <<'EOF'

# Interactive shells only, never into a pipe, never on a dumb console.
[[ -o interactive ]] || return 0
[[ -t 1 ]] || return 0
case "${TERM:-dumb}" in linux|dumb|vt100|vt220) return 0 ;; esac

# tmux swallows OSC unless wrapped in a DCS passthrough envelope, with every
# inner ESC doubled.
_tc_seq() {
  if [[ -n "${TMUX:-}" ]]; then
    printf '\033Ptmux;\033\033]%s\a\033\\' "$1"
  else
    printf '\033]%s\a' "$1"
  fi
}

_tabcolor() {
  # Title marker: every terminal (this is what Ghostty can show).
  _tc_seq "2;${TC_MARK}"
  # Real tab colour: iTerm2 only (proprietary sequence).
  [[ "${LC_TERMINAL:-}" = "iTerm2" ]] || return 0
  _tc_seq "6;1;bg;red;brightness;${TC_R}"
  _tc_seq "6;1;bg;green;brightness;${TC_G}"
  _tc_seq "6;1;bg;blue;brightness;${TC_B}"
}

# Repaint before every prompt, so nested hops heal themselves.
autoload -Uz add-zsh-hook
add-zsh-hook precmd _tabcolor
EOF
} > "$FILE"
echo "[1/3] wrote $FILE"

touch "$ZSHRC"
if ! grep -q '>>> tabcolor >>>' "$ZSHRC"; then
  {
    echo ""
    echo "# >>> tabcolor >>>"
    echo "[ -f \"\$HOME/.config/tabcolor/tabcolor.zsh\" ] && source \"\$HOME/.config/tabcolor/tabcolor.zsh\""
    echo "# <<< tabcolor <<<"
  } >> "$ZSHRC"
  echo "[2/3] added the source line to $ZSHRC"
else
  echo "[2/3] $ZSHRC already sources it"
fi

# Ghostty's own shell integration resets the title at every prompt unless its
# title feature is off. The macOS app reads this file, not ~/.config/ghostty/config.
GCFG="$HOME/Library/Application Support/com.mitchellh.ghostty/config.ghostty"
if [ -d "$(dirname "$GCFG")" ]; then
  if grep -q '^shell-integration-features *=.*no-title' "$GCFG" 2>/dev/null; then
    echo "[3/3] Ghostty already has no-title"
  else
    echo 'shell-integration-features = no-title' >> "$GCFG"
    echo "[3/3] added 'shell-integration-features = no-title' to Ghostty's config (quit and reopen Ghostty)"
  fi
else
  echo "[3/3] Ghostty not installed here, skipped"
fi

echo
echo "Open a NEW terminal tab to see: $EMOJI $NAME"
